import 'package:capywake/core/models/dismiss_method.dart';
import 'package:capywake/core/models/wake_mode.dart';
import 'package:capywake/core/puzzle/alarm_puzzle_override.dart';
import 'package:capywake/core/puzzle/puzzle_settings.dart';
import 'package:meta/meta.dart';

/// A user-configured alarm.
///
/// Pure-Dart, immutable, value-equal — the source of truth for what the user
/// asked for. The schedule engine (Phase 05) turns this into concrete
/// `AlarmOccurrence`s; this model itself never carries derived state like
/// "next fire time" — derived data is computed on demand to stay honest.
///
/// Time semantics:
/// - [targetTimeMinutes] is **minutes since local midnight** (0..1439). All
///   clock times in CapyWake are stored this way and formatted to a display
///   string only at the UI boundary via `intl`.
/// - [repeatWeekdays] uses the ISO 8601 convention (Monday = 1 .. Sunday = 7).
///   An empty set means "one-time alarm" (fires on the next occurrence of
///   [targetTimeMinutes] and is then disabled by the lifecycle layer).
/// - All durations are **integer minutes**.
///
/// Validation invariants are enforced in the constructor — bad input fails
/// fast in tests rather than silently producing nonsense schedules at 03:00.
@immutable
class Alarm {
  Alarm({
    required this.id,
    required this.label,
    required this.enabled,
    required this.targetTimeMinutes,
    required this.repeatWeekdays,
    required this.wakeMode,
    required this.wakeWindowStartMinutesBefore,
    required this.soundId,
    required this.vibrationEnabled,
    required this.snoozeEnabled,
    required this.snoozeDurationMinutes,
    required this.maxSnoozes,
    required this.dismissMethod,
    required this.dismissChallengeDifficulty,
    required this.confirmationEnabled,
    required this.createdAt,
    required this.updatedAt,
    this.puzzleOverride,
    this.motionConfirmationEnabled = false,
  }) : assert(
         targetTimeMinutes >= 0 && targetTimeMinutes < 24 * 60,
         'targetTimeMinutes must be in [0, 1440).',
       ),
       assert(
         wakeWindowStartMinutesBefore >= 0,
         'wakeWindowStartMinutesBefore must be >= 0.',
       ),
       assert(
         snoozeDurationMinutes >= 0,
         'snoozeDurationMinutes must be >= 0.',
       ),
       assert(
         maxSnoozes == null || maxSnoozes >= 0,
         'maxSnoozes must be null (unlimited) or >= 0.',
       ),
       assert(
         repeatWeekdays.every((d) => d >= 1 && d <= 7),
         'repeatWeekdays values must be in [1, 7].',
       ) {
    // Defensive: an alarm using a non-challenge dismiss method should not
    // carry a challenge difficulty (it would be silently ignored). Surface it
    // here so corrupt data fails the round-trip test instead of a UI bug.
    if (dismissChallengeDifficulty != null &&
        dismissMethod != DismissMethod.puzzle) {
      throw ArgumentError(
        'dismissChallengeDifficulty is only meaningful when dismissMethod '
        'is a challenge method (puzzle); got $dismissMethod.',
      );
    }
    if (puzzleOverride != null && dismissMethod != DismissMethod.puzzle) {
      throw ArgumentError(
        'puzzleOverride is only meaningful when dismissMethod is puzzle; '
        'got $dismissMethod.',
      );
    }
  }

  /// Stable id (UUID) — survives edits. Generated by the data layer when an
  /// alarm is first created.
  final String id;

  /// User-supplied label, e.g. "Workdays" or "Yoga". May be empty.
  final String label;

  /// Whether the alarm is currently armed. A disabled alarm produces no
  /// occurrences.
  final bool enabled;

  /// Local-time target, **minutes since midnight** (0..1439).
  final int targetTimeMinutes;

  /// ISO 8601 weekdays (Monday = 1 .. Sunday = 7) on which the alarm
  /// repeats. Empty set = one-time alarm.
  final Set<int> repeatWeekdays;

  /// Wake mode (Gentle / Standard / Strict). Controls escalation, default
  /// snooze rules, and confirmation behaviour.
  final WakeMode wakeMode;

  /// How many minutes before the target the wake window starts (soft-start).
  /// `0` means no soft-start.
  final int wakeWindowStartMinutesBefore;

  /// Sound asset identifier (the asset registry lives in the sound phase;
  /// for now this is just the chosen id). May be empty for "vibration only".
  final String soundId;

  /// Whether vibration is enabled for this alarm.
  final bool vibrationEnabled;

  /// Whether snoozing is permitted at all.
  final bool snoozeEnabled;

  /// Snooze interval in minutes when [snoozeEnabled] is true.
  final int snoozeDurationMinutes;

  /// Max snoozes before the no-snooze final alarm; `null` means unlimited.
  ///
  /// The ring that takes the occurrence to this cap is CapyWake's **final
  /// alarm**: it is offered without a Snooze button, so a long string of
  /// snoozes still ends in a ring the user has to answer. `null` (unlimited)
  /// means there is no final alarm on this one.
  final int? maxSnoozes;

  /// How a ringing alarm is dismissed.
  final DismissMethod dismissMethod;

  /// Difficulty of the wake puzzle on this alarm.
  ///
  /// Only meaningful when [dismissMethod] is `puzzle`. `null` means **follow
  /// the app-wide puzzle difficulty** — the same rule every field of
  /// [puzzleOverride] uses, so there is one mental model for "this alarm has
  /// not been customised here".
  final DismissChallengeDifficulty? dismissChallengeDifficulty;

  /// This alarm's departures from the app-wide puzzle settings, or `null` when
  /// it simply follows them.
  ///
  /// Only meaningful when [dismissMethod] is `puzzle`. See
  /// [AlarmPuzzleOverride] for why difficulty is carried separately.
  final AlarmPuzzleOverride? puzzleOverride;

  /// Whether the "still up?" confirmation runs after dismiss. Strict mode
  /// turns this on by default; users can override per-alarm.
  final bool confirmationEnabled;

  /// Whether CapyWake watches for phone movement after this alarm is stopped,
  /// and rings once more if it sees none.
  ///
  /// Deliberately a **sibling** of [confirmationEnabled] rather than a
  /// modifier of it. The two are different confirmations of the same thing and
  /// only one can run: when this is on the tap screen never appears, because a
  /// tap is exactly what a half-asleep person can do without being up. Making
  /// it a modifier would have chained it to a flag no form exposes (only the
  /// wake mode sets [confirmationEnabled]), so turning the motion check on
  /// would have silently depended on picking Strict.
  ///
  /// Gated twice: this per-alarm switch and the global
  /// `UserSettings.motionConfirmationEnabled` kill switch, which wins. Both
  /// default to off, so the feature is inert until asked for.
  final bool motionConfirmationEnabled;

  /// When the alarm row was first created (UTC).
  final DateTime createdAt;

  /// When the alarm row was last edited (UTC). Updated by the data layer on
  /// every write.
  final DateTime updatedAt;

  /// Returns a copy with the given fields replaced.
  ///
  /// To clear an optional field (e.g. set [dismissChallengeDifficulty] back
  /// to `null` after switching from a challenge dismiss method), pass a
  /// "clear" flag: `copyWith(clearDismissChallengeDifficulty: true)`. This is
  /// the standard Dart workaround for "the user passed `null` on purpose"
  /// vs. "the user did not specify the field at all".
  Alarm copyWith({
    String? id,
    String? label,
    bool? enabled,
    int? targetTimeMinutes,
    Set<int>? repeatWeekdays,
    WakeMode? wakeMode,
    int? wakeWindowStartMinutesBefore,
    String? soundId,
    bool? vibrationEnabled,
    bool? snoozeEnabled,
    int? snoozeDurationMinutes,
    int? maxSnoozes,
    bool clearMaxSnoozes = false,
    DismissMethod? dismissMethod,
    DismissChallengeDifficulty? dismissChallengeDifficulty,
    bool clearDismissChallengeDifficulty = false,
    AlarmPuzzleOverride? puzzleOverride,
    bool clearPuzzleOverride = false,
    bool? confirmationEnabled,
    bool? motionConfirmationEnabled,
    DateTime? createdAt,
    DateTime? updatedAt,
  }) {
    return Alarm(
      id: id ?? this.id,
      label: label ?? this.label,
      enabled: enabled ?? this.enabled,
      targetTimeMinutes: targetTimeMinutes ?? this.targetTimeMinutes,
      repeatWeekdays: repeatWeekdays ?? this.repeatWeekdays,
      wakeMode: wakeMode ?? this.wakeMode,
      wakeWindowStartMinutesBefore:
          wakeWindowStartMinutesBefore ?? this.wakeWindowStartMinutesBefore,
      soundId: soundId ?? this.soundId,
      vibrationEnabled: vibrationEnabled ?? this.vibrationEnabled,
      snoozeEnabled: snoozeEnabled ?? this.snoozeEnabled,
      snoozeDurationMinutes:
          snoozeDurationMinutes ?? this.snoozeDurationMinutes,
      maxSnoozes: clearMaxSnoozes ? null : (maxSnoozes ?? this.maxSnoozes),
      dismissMethod: dismissMethod ?? this.dismissMethod,
      dismissChallengeDifficulty: clearDismissChallengeDifficulty
          ? null
          : (dismissChallengeDifficulty ?? this.dismissChallengeDifficulty),
      puzzleOverride: clearPuzzleOverride
          ? null
          : (puzzleOverride ?? this.puzzleOverride),
      confirmationEnabled: confirmationEnabled ?? this.confirmationEnabled,
      motionConfirmationEnabled:
          motionConfirmationEnabled ?? this.motionConfirmationEnabled,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  /// The puzzle configuration this alarm should actually wake someone with.
  ///
  /// Layers [puzzleOverride] and [dismissChallengeDifficulty] over the
  /// app-wide [defaults]; anything this alarm has not customised keeps
  /// tracking the defaults as the user edits them in Settings.
  PuzzleSettings resolvePuzzleSettings(PuzzleSettings defaults) {
    return AlarmPuzzleOverride.resolveFor(
      defaults: defaults,
      override: puzzleOverride,
      difficulty: dismissChallengeDifficulty,
    );
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is Alarm &&
        other.id == id &&
        other.label == label &&
        other.enabled == enabled &&
        other.targetTimeMinutes == targetTimeMinutes &&
        _setEquals(other.repeatWeekdays, repeatWeekdays) &&
        other.wakeMode == wakeMode &&
        other.wakeWindowStartMinutesBefore == wakeWindowStartMinutesBefore &&
        other.soundId == soundId &&
        other.vibrationEnabled == vibrationEnabled &&
        other.snoozeEnabled == snoozeEnabled &&
        other.snoozeDurationMinutes == snoozeDurationMinutes &&
        other.maxSnoozes == maxSnoozes &&
        other.dismissMethod == dismissMethod &&
        other.dismissChallengeDifficulty == dismissChallengeDifficulty &&
        other.puzzleOverride == puzzleOverride &&
        other.confirmationEnabled == confirmationEnabled &&
        other.motionConfirmationEnabled == motionConfirmationEnabled &&
        other.createdAt == createdAt &&
        other.updatedAt == updatedAt;
  }

  @override
  int get hashCode => Object.hashAll([
    id,
    label,
    enabled,
    targetTimeMinutes,
    // Hash the repeat-weekday set order-independently.
    Object.hashAllUnordered(repeatWeekdays),
    wakeMode,
    wakeWindowStartMinutesBefore,
    soundId,
    vibrationEnabled,
    snoozeEnabled,
    snoozeDurationMinutes,
    maxSnoozes,
    dismissMethod,
    dismissChallengeDifficulty,
    puzzleOverride,
    confirmationEnabled,
    motionConfirmationEnabled,
    createdAt,
    updatedAt,
  ]);
}

bool _setEquals<T>(Set<T> a, Set<T> b) {
  if (identical(a, b)) return true;
  if (a.length != b.length) return false;
  for (final v in a) {
    if (!b.contains(v)) return false;
  }
  return true;
}
